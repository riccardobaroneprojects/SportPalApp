import type { Metadata } from "next";
import PlayerLayoutWrapper from "@/app/(player)/PlayerLayoutWrapper";
import createServerSupabaseClient from "@/supabase/createClients/serverClient";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const supabase = await createServerSupabaseClient();

  const {
    data: { user },
  } = await supabase.auth.getUser();

  let initialCenter = null;

  if (user?.user_metadata?.latitude && user?.user_metadata?.longitude) {
    initialCenter = {
      lat: user.user_metadata.latitude,
      lon: user.user_metadata.longitude,
    };
  }

  return (
    <div className="">
      <PlayerLayoutWrapper initialCenter={initialCenter}>
        {children}
      </PlayerLayoutWrapper>
    </div>
  );
}
